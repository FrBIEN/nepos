import { build } from 'esbuild';
import { mkdtemp, readFile, writeFile, rm, mkdir } from 'node:fs/promises';
import { readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
const filiusHome = process.env.FILIUS_HOME ?? '..';
const dir=await mkdtemp(join(tmpdir(),'nepos-java-'));
try {
    const module=join(dir,'codec.mjs');await build({entryPoints:['src/scenario/ProjectCodec.ts'],outfile:module,bundle:true,platform:'node',format:'esm'});
    const {decodeProject,encodeProject}=await import(pathToFileURL(module));
    const zipModule=join(dir,'zip.mjs');await build({entryPoints:['src/scenario/fls/ZipArchive.ts'],outfile:zipModule,bundle:true,platform:'node',format:'esm'});
    const {readZip}=await import(pathToFileURL(zipModule));
    const argumentsXML=[];
    for(const name of readdirSync(join(filiusHome,'beispiele')).filter(n=>n.endsWith('.fls'))){const {scenario}=await decodeProject(new Uint8Array(await readFile(join(filiusHome,'beispiele',name))),name);const zip=await readZip(encodeProject(scenario,'fls').bytes);const file=join(dir,name+'.xml');await writeFile(file,zip.get('projekt/konfiguration.xml'));argumentsXML.push(file);}
    const example=JSON.parse(await readFile('public/examples/lernnetz.json','utf8'));example.name='Nepos – Grüße 🌐';
    example.serviceState.webServers[0].files[0].content='Grüße 🌐 <p>XML & Daten</p>\u0000';
    const unicode=await readZip(encodeProject(example,'fls').bytes),unicodeFile=join(dir,'nepos-unicode.xml');await writeFile(unicodeFile,unicode.get('projekt/konfiguration.xml'));argumentsXML.push(unicodeFile);
    for(const [index,path] of process.argv.slice(2).entries()){
        const input=new Uint8Array(await readFile(path)),{scenario}=await decodeProject(input,path),original=await readZip(input),regenerated=await readZip(encodeProject(scenario,'fls').bytes);
        const xml=original.get('projekt/konfiguration.xml');
        if(!xml||!Buffer.from(xml).equals(Buffer.from(regenerated.get('projekt/konfiguration.xml'))))throw new Error('Java check accepts only unchanged XML generated by this Nepos exporter');
        const file=join(dir,`browser-export-${index}.xml`);await writeFile(file,xml);argumentsXML.push(file);
    }
    const source=await readFile('scripts/VerifyFls.java','utf8');const java=join(dir,'VerifyFls.java');await writeFile(java,source);const home=join(dir,'home');await mkdir(home);
    const output=execFileSync('java',['-Djava.awt.headless=true','-Duser.home='+home,'-cp',resolve(filiusHome,'target/classes')+':'+resolve(filiusHome,'target/lib')+'/*',java,...argumentsXML],{encoding:'utf8',maxBuffer:20*1024*1024,timeout:60000,killSignal:'SIGKILL'});
    console.log(output.split('\n').filter(line=>line.startsWith('PASS:')).join('\n'));
}finally{await rm(dir,{recursive:true,force:true});}
